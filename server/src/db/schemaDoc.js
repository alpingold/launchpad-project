/**
 * A column's comment ("-- ...") and CHECK rule from its line in the CREATE TABLE text. SQLite
 * keeps that text as it was written, so the comments in schema.sql and migrations.js come along.
 * @returns {{ comment: string, check: string | null, nocase: boolean }}
 */
function columnExtras(tableSql, column) {
  for (const line of tableSql.split('\n')) {
    const [code, ...comment] = line.split('--');
    // A column added later (ALTER TABLE ... ADD COLUMN) is appended to the LAST line, after
    // a comma: so each line is split into its column definitions first (commas outside brackets).
    const parts = splitTopLevel(code);
    const part = parts.find((p) => /^\s*"?(\w+)"?\s/.exec(p)?.[1] === column);
    if (part !== undefined) {
      const check = /CHECK\s*(\(.*\))/i.exec(part);
      return {
        comment: part === parts[0] ? comment.join('--').trim() : '', // a line's comment is about its first column
        check: check ? `check ${check[1].replace(/\)\s*,?\s*$/, ')')}` : null,
        nocase: /COLLATE\s+NOCASE/i.test(part),
      };
    }
  }
  return { comment: '', check: null, nocase: false };
}

/** "a INTEGER, b TEXT CHECK (b IN ('x', 'y'))" → ["a INTEGER", " b TEXT CHECK (b IN ('x', 'y'))"] */
function splitTopLevel(code) {
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < code.length; i++) {
    if (code[i] === '(') depth++;
    else if (code[i] === ')') depth--;
    else if (code[i] === ',' && depth === 0) {
      parts.push(code.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(code.slice(start));
  return parts;
}

/** @returns {string} the whole SCHEMA.md */
export function describeSchema() {
  const db = openDatabase(':memory:');
  try {
    const tables = db.prepare("SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all();
    const out = [
      '# Database schema',
      '',
      `<!-- Generated by \`npm run schema\` from a fresh database (schema.sql + migrations.js). Don't edit by hand. -->`,
      '',
      `The database is at **version ${LATEST_VERSION}**. \`schema.sql\` made version 1 (users and sessions);`,
      'every later change is a migration in `migrations.js`, run once on startup by any database that',
      "doesn't have it yet (with a backup first). To change the schema, add a migration, then run",
      '`npm run schema`.',
      '',
      '| Version | Change |',
      '|---|---|',
      '| 1 | accounts and login sessions (`schema.sql`, M7) |',
      ...MIGRATIONS.map((m) => `| ${m.version} | ${m.description} |`),
      '',
    ];
    for (const { name, sql } of tables) {
      out.push(`## ${name}`, '', TABLE_NOTES[name] ?? '', '');
      const fks = new Map(db.prepare(`PRAGMA foreign_key_list("${name}")`).all().map((fk) => [fk.from, `→ ${fk.table}.${fk.to}${fk.on_delete !== 'NO ACTION' ? ` (on delete: ${fk.on_delete.toLowerCase()})` : ''}`]));
      out.push('| Column | Type | Rules | Notes |', '|---|---|---|---|');
      const columns = db.prepare(`PRAGMA table_info("${name}")`).all();
      const keyParts = columns.filter((c) => c.pk).length;
      // Columns that must be unique on their own (UNIQUE in the CREATE TABLE).
      const unique = new Set(
        db
          .prepare(`PRAGMA index_list("${name}")`)
          .all()
          .filter((i) => i.origin === 'u')
          .map((i) => db.prepare(`PRAGMA index_info("${i.name}")`).all())
          .filter((cols) => cols.length === 1)
          .map((cols) => cols[0].name),
      );
      for (const col of columns) {
        const { comment, check, nocase } = columnExtras(sql, col.name);
        const rules = [
          col.pk ? (keyParts > 1 ? 'part of the primary key' : 'primary key') : null,
          unique.has(col.name) ? 'unique' : null,
          nocase ? 'any capitalization counts as the same' : null,
          col.notnull ? 'not null' : null,
          col.dflt_value !== null ? `default ${col.dflt_value}` : null,
          fks.get(col.name) ?? null,
          check,
        ]
          .filter(Boolean)
          .join(', ');
        const cell = (text) => text.replaceAll('|', '\\|');
        out.push(`| \`${col.name}\` | ${col.type || 'any'} | ${cell(rules)} | ${cell(comment)} |`);
      }
      const indexes = db.prepare(`PRAGMA index_list("${name}")`).all().filter((i) => i.origin === 'c');
      for (const index of indexes) {
        const cols = db.prepare(`PRAGMA index_info("${index.name}")`).all().map((c) => c.name);
        out.push('', `Index \`${index.name}\` on ${cols.map((c) => `\`${c}\``).join(', ')}.`);
      }
      out.push('');
    }
    return `${out.join('\n').trimEnd()}\n`;
  } finally {
    db.close();
  }
}
